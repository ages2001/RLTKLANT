#!/usr/bin/env python3
"""
mkinfids.py - regenerate the model lines and the device names of
bin/2KXP/netrtlk.inf from the driver's own id tables (src/rtlchip.h
RtlPciIds[] and USBNT/src/usbchip.h RtlUsbIds[]), so the INF never offers
an id the driver rejects or misses one it drives.

PCI rows whose vendor is RTL_PCI_ANY (8139 cards with a broken vendor id)
cannot be written as an INF hardware id; they are listed for vendor 0001,
the broken id 8139too names.  A row that fixes only the subsystem device
gets the subsystem vendor of its board vendor when that is known
(Linksys EG1032), else no SUBSYS part (the driver still checks it).

Usage:  python3 tools/mkinfids.py [--check]
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INF = ROOT / "bin" / "2KXP" / "netrtlk.inf"
ANY = 0xFFFF
BROKEN_VENDOR = 0x0001          # 8139too: "cards report invalid vendor ids like 0x0001"


def c_rows(path, table):
    text = path.read_text()
    body = text[text.index(table):]
    body = body[body.index("{") + 1:body.index("\n};")]
    return body


def pci_ids():
    body = c_rows(ROOT / "src" / "rtlchip.h", "static const RTL_PCI_ID RtlPciIds[]")
    defs = {"RTL_VENDOR_ID": 0x10EC, "RTL_PCI_ANY": ANY}
    num = lambda t: defs[t.strip()] if t.strip() in defs else int(t, 0)
    out = []
    for m in re.finditer(r'RTL_PCI_REALTEK\((\w+),[^"]*"([^"]*)"\)', body):
        out.append((m.start(), 0x10EC, num(m.group(1)), ANY, ANY, m.group(2)))
    for m in re.finditer(r'RTL_PCI_OEM\((\w+),\s*(\w+),[^"]*"([^"]*)"\)', body):
        out.append((m.start(), num(m.group(1)), num(m.group(2)), ANY, ANY, m.group(3)))
    for m in re.finditer(r'RTL_PCI_SUB\((\w+),\s*(\w+),\s*(\w+),\s*(\w+),[^"]*"([^"]*)"\)', body):
        out.append((m.start(),) + tuple(num(m.group(i)) for i in range(1, 5)) + (m.group(5),))
    for m in re.finditer(r'\{\s*(RTL_VENDOR_ID|0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(\w+),\s*(\w+),'
                         r'[^"]*"([^"]*)"\s*\}', body):
        out.append((m.start(),) + tuple(num(m.group(i)) for i in range(1, 5)) + (m.group(5),))
    return sorted(out)


def pci_hwid(v, d, sv, sd):
    if v == ANY:
        v = BROKEN_VENDOR
    hw = "PCI\\VEN_%04X&DEV_%04X" % (v, d)
    if sd != ANY:
        if sv == ANY:
            sv = v if v not in (BROKEN_VENDOR,) else None
        if sv is not None:
            hw += "&SUBSYS_%04X%04X" % (sd, sv)
    return hw


def usb_ids():
    body = c_rows(ROOT / "USBNT" / "src" / "usbchip.h", "static const RTL_USB_ID RtlUsbIds[]")
    out = []
    for m in re.finditer(r'RTLU_ROW(?:8150)?\((0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),[^"]*"([^"]*)"\)', body):
        out.append((int(m.group(1), 16), int(m.group(2), 16), m.group(3)))
    return out


def main():
    pci = []
    seen = set()
    for pos, v, d, sv, sd, name in pci_ids():
        hw = pci_hwid(v, d, sv, sd)
        if hw in seen:
            continue
        seen.add(hw)
        key = "D_%04X" % d if (v == 0x10EC and sd == ANY) else \
              "D_" + hw.split("\\")[1].replace("VEN_", "").replace("DEV_", "").replace("SUBSYS_", "").replace("&", "_")
        pci.append((pos, key, hw, name))
    usb = []
    for v, p, name in usb_ids():
        key = "U_%04X" % p if v == 0x0BDA else "U_%04X_%04X" % (v, p)
        usb.append((key, "USB\\VID_%04X&PID_%04X" % (v, p), name))

    def models():
        lines = ["; PCI / PCIe (src/rtlchip.h; generated by tools/mkinfids.py)"]
        width = max(len(k) for _, k, _, _ in pci) + 2
        for _, key, hw, _ in pci:
            lines.append(("%%%s%%" % key).ljust(width) + " = RTL.ndi,    " + hw)
        lines.append("; USB (USBNT/src/usbchip.h; generated by tools/mkinfids.py)")
        width = max(len(k) for k, _, _ in usb) + 2
        for key, hw, _ in usb:
            lines.append(("%%%s%%" % key).ljust(width) + " = RTLUSB.ndi, " + hw)
        return lines

    names = ["; --- PCI / PCIe names (generated by tools/mkinfids.py) ---"]
    done = set()
    for _, key, _, name in pci:
        if key not in done:
            names.append('%s="%s"' % (key, name)); done.add(key)
    names.append("; --- USB names (generated by tools/mkinfids.py) ---")
    for key, _, name in usb:
        if key not in done:
            names.append('%s="%s"' % (key, name)); done.add(key)

    raw = INF.read_bytes().decode("ascii")
    nl = "\r\n" if "\r\n" in raw else "\n"
    lines = raw.split(nl)

    def replace_section(lines, header, body):
        i = lines.index(header) + 1
        j = i
        while j < len(lines) and not lines[j].startswith("["):
            j += 1
        # keep the trailing blank / comment lines that introduce the next section
        k = j
        while k > i and (lines[k - 1] == "" or (lines[k - 1].startswith("; ") and
                                                  ("=" * 5 in lines[k - 1] or "-" * 4 in lines[k - 1]))):
            k -= 1
        return lines[:i] + body + lines[k:]

    lines = replace_section(lines, "[Realtek]", models())
    lines = replace_section(lines, "[Realtek.NTamd64]", models())
    s = lines.index("[Strings]")
    start = next(i for i in range(s, len(lines)) if lines[i].startswith("; --- PCI"))
    end = start
    while end < len(lines) and (lines[end].startswith(("D_", "U_", "; --- PCI", "; --- USB"))):
        end += 1
    lines = lines[:start] + names + lines[end:]
    out = nl.join(lines)
    if "--check" in sys.argv:
        if out != raw:
            sys.exit("netrtlk.inf models are stale: run tools/mkinfids.py")
        print("netrtlk.inf models match the id tables")
        return
    INF.write_bytes(out.encode("ascii"))
    print("netrtlk.inf: %d PCI and %d USB hardware ids" % (len(pci), len(usb)))


if __name__ == "__main__":
    main()
