"""Embed immutable licensed payloads; reject changed/missing manifest inputs."""
from pathlib import Path
import hashlib,json,sys
root=Path(__file__).resolve().parents[1];fw=root/'firmware'
manifest=json.loads((fw/'manifest.json').read_text())
catalog=json.loads((fw/'chips.json').read_text())
lines=['/* Generated by build/make-fwimages.py. Do not edit. Payload copyright',
       ' * and redistribution terms: firmware/LICENSE.r8169; retain that file.',
       ' * Primary XID facts: firmware/chips.json. No silicon support claim. */',
       '#include "fwimages.h"']
indices={}
for index,record in enumerate(manifest['files']):
    name=record['path'];assert name.startswith('rtl_nic/') and '..' not in name
    data=(fw/name).read_bytes()
    assert len(data)==record['size'] and hashlib.sha256(data).hexdigest()==record['sha256'], name
    indices[name]=index;lines.append('static const RTL_FW_U8 fw%d[]={'%index)
    for offset in range(0,len(data),16):
        lines.append(','.join('0x%02x'%x for x in data[offset:offset+16])+',')
    lines.append('};')
lines.append('static const RTL_FW_IMAGE images[]={')
for name,index in indices.items():lines.append('{"%s",fw%d,sizeof(fw%d)},'%(name,index,index))
lines+=['};','static const RTL_FW_CHIP chips[]={']
for c in catalog['chips']:
    image='&images[%d]'%indices[c['firmware']] if c['firmware'] else '0'
    lines.append('{0x%x,0x%x,%d,%s},'%(c['mask'],c['xid'],c['mac_version'],image))
lines+=['};','static const RTL_FW_CHIP fast[]={']
for c in catalog['fast_ethernet_overrides']:
    lines.append('{0,0,%d,&images[%d]},'%(c['replacement_version'],indices[c['firmware']]))
lines+=['};','static const RTL_FW_CHIP ext[]={']
for c in catalog['extended_chips']:
    image='&images[%d]'%indices[c['firmware']] if c['firmware'] else '0'
    lines.append('{0,0,%d,%s},'%(c['mac_version'],image))
marker=catalog['extended_marker']
lines+=['};',
        '/* Primary XIDs that only say "read TX_CONFIG_V2" (Linux RTL_GIGA_MAC_VER_EXTENDED). */',
        'int RtlFwXidIsExtended(RTL_FW_U16 xid)','{',
        ' return xid<=0xfff&&(xid&0x%x)==0x%x;'%(marker['mask'],marker['xid']),'}',
        '/* TX_CONFIG_V2 value -> RTL_FW_XID_EXTENDED+row, or RTL_FW_XID_UNKNOWN. */',
        'RTL_FW_U16 RtlFwExtendedXid(RTL_FW_U32 xid2)','{']
for i,c in enumerate(catalog['extended_chips']):
    lines.append(' if((xid2&0x%xUL)==0x%xUL)return (RTL_FW_U16)(RTL_FW_XID_EXTENDED+%d);'%(c['mask'],c['xid2'],i))
lines+=[' return RTL_FW_XID_UNKNOWN;','}',
        'const RTL_FW_CHIP *RtlFwChip(RTL_FW_U16 xid,int gmii)','{',
        ' unsigned i;',
        ' if(xid>=RTL_FW_XID_EXTENDED&&xid<RTL_FW_XID_EXTENDED+sizeof(ext)/sizeof(ext[0]))return &ext[xid-RTL_FW_XID_EXTENDED];',
        ' if(xid>0xfff)return 0;',
        ' for(i=0;i<sizeof(chips)/sizeof(chips[0]);i++){',
        '  const RTL_FW_CHIP*c=&chips[i];if((xid&c->Mask)!=c->Xid)continue;']
for i,c in enumerate(catalog['fast_ethernet_overrides']):
    lines.append('  if(!gmii&&c->MacVersion==%d)return &fast[%d];'%(c['mac_version'],i))
lines+=['  return c;',' }',' return 0;','}']
output='\n'.join(lines)+'\n';target=root/'src/fwimages.c'
if '--check' in sys.argv:
    assert target.read_text()==output, 'Generated firmware image source is stale'
else:target.write_text(output)
print('Verified %d payload hashes; %d primary and %d extended silicon rows'%(len(indices),len(catalog['chips']),len(catalog['extended_chips'])))
